function familyFromHex(hex?: string, name = ""): string {
  if (!hex || !/^#[0-9A-Fa-f]{6}$/.test(hex)) return "Other";
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2 / 255;
  const d = max - min;
  const sat = max === 0 ? 0 : d / 255;
  const n = name.toLowerCase();
  if (l > 0.9 && sat < 0.12) {
    return n.includes("off") || n.includes("cream") || n.includes("ivory")
      ? "Off Whites"
      : "Whites";
  }
  if (l > 0.82 && sat < 0.2) return "Off Whites";
  if (sat < 0.12) return "Grey";
  let h = 0;
  if (d !== 0) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  if (h < 15 || h >= 345) return "Red";
  if (h < 40) return "Orange";
  if (h < 70) return "Yellow";
  if (h < 160) return "Green";
  if (h < 255) return "Blue";
  if (h < 290) return "Purple";
  if (h < 345) return "Pink";
  return "Brown";
}

export function getPaintShadeFamily(shade: {
  brand: string;
  code: string;
  hex?: string;
  name: string;
}): string {
  const key = `${shade.brand}|${shade.code}`;
  return FAMILY_BY_KEY[key] || familyFromHex(shade.hex, shade.name);
}
